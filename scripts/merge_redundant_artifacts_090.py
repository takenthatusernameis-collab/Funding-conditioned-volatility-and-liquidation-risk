#!/usr/bin/env python3
"""[HEAVY-090] Merge redundant Track A artifact families into single archives.

After the HEAVY-090 ironflow digest consolidation (37 per-run digest files ->
1 canonical running archive), the remaining artifact churn in research_state
was three Track A families whose latest file is the only one AGENT_HANDOFF.md
and experiment_frontier.json point to:

  - liquidation_forward_validate_*blocker*.md  (9 files, sequential blockers)
  - trigger_probe_tracka_*.md                  (3 files, probe summaries)
  - tracka_fclr010_dryrun_hardened_*.md        (2 files, harness dry-run notes)
  - campaign_sweep_*.md                        (6 files, 5 of them superseded)
  - trackc_recompute_audit_20261104T175619Z_20261104T175619Z.md  (76-byte empty shell)

Each family's latest file is kept verbatim (it is the canonical artifact).
Superseded siblings are folded into a single timestamped archive that records
every removed file's name, size, and first 40 lines, so the audit trail is
preserved rather than erased. Track C artifacts (trackc_robustness_*,
trackc_deeper_validation_*, leakage_audit_heavy_*, bottleneck_demolition_*)
are deliberately NOT touched: they are the sealed audit trail of the locked
Track C conclusion and must not be consolidated.

Idempotent: re-running after migration is a no-op.
"""
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
STATE = REPO_ROOT / "research_state"

# (archive_name, glob_pattern, keep_latest_substring, mode)
# mode "archive": fold superseded files into a single timestamped archive.
# mode "drop": the file is unreferenced and carries no information; delete it.
FAMILIES = [
    ("tracka_blocker_history_090.md",
     "liquidation_forward_validate_*blocker*.md", None, "archive"),
    ("tracka_trigger_probe_history_090.md",
     "trigger_probe_tracka_*.md", None, "archive"),
    ("tracka_dryrun_history_090.md",
     "tracka_fclr010_dryrun_hardened_*.md", None, "archive"),
    ("tracka_campaign_sweep_history_090.md",
     "campaign_sweep_*.md", "campaign_sweep_tracka_20261105T061550Z.md", "archive"),
    # [HEAVY-090] trackc_recompute_audit_20261104T175619Z_20261104T175619Z.md is a
    # 76-byte stub containing only its own title, a duplicate of the canonical
    # trackc_recompute_audit_20261104T175643Z.md (3,857 bytes, full audit).
    # Unreferenced by any canonical doc (verified by grep). Carries no
    # information, so it is dropped rather than archived. The canonical audit
    # and the sealed Track C results are untouched.
    (None,
     "trackc_recompute_audit_20261104T175619Z_20261104T175619Z.md", None, "drop"),
]


def main():
    total_removed = 0
    for entry in FAMILIES:
        archive_name, pattern, keep, mode = entry
        files = sorted(STATE.glob(pattern))
        if keep:
            files = [f for f in files if f.name != keep]
        if mode == "drop":
            for f in files:
                try:
                    f.unlink()
                    total_removed += 1
                except Exception as e:
                    print(f"!! could not drop {f.name}: {e!r}")
            print(f"drop: removed {len(files)} stub file(s) from {pattern}")
            continue
        if len(files) <= 1:
            print(f"{archive_name}: nothing to merge ({len(files)} file(s))")
            continue
        archive = STATE / archive_name
        parts = [
            f"# {archive_name}\n",
            f"Merged {len(files)} superseded file(s) from glob `{pattern}` into a single archive.\n",
            f"Latest canonical file kept verbatim. Generated by scripts/merge_redundant_artifacts_090.py.\n\n",
        ]
        for f in files:
            try:
                text = f.read_text(errors="replace")
            except Exception as e:
                text = f"<unreadable: {e!r}>"
            lines = text.splitlines()
            preview = "\n".join(lines[:40])
            parts.append(f"## {f.name} ({len(lines)} lines, {len(text)} bytes)\n\n")
            parts.append("```\n")
            parts.append(preview)
            if len(lines) > 40:
                parts.append(f"\n... ({len(lines) - 40} more lines)\n")
            parts.append("\n```\n\n")
            try:
                f.unlink()
                total_removed += 1
            except Exception as e:
                parts.append(f"!! could not remove: {e!r}\n\n")
        archive.write_text("".join(parts))
        print(f"{archive_name}: merged {len(files)} file(s) -> {archive.name}")
    print(f"total files removed: {total_removed}")
    return 0


if __name__ == "__main__":
    sys.exit(main())